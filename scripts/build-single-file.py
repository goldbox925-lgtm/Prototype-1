"""Bundle the multi-file prototype into ONE self-contained HTML file: playmode-prototype.html.
Usage:  python3 scripts/build-single-file.py            (run from the project folder)
Inlines css/app.css, every <script src>, config.js and the theme illustrations (assets/themes/*.svg).
The Supabase client is NOT inlined: in live mode it is loaded from a CDN at runtime (demo mode needs no network)."""
import re, os, glob, urllib.parse, json, sys
SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(SRC, 'playmode-prototype.html')
assets = {}
for f in sorted(glob.glob(SRC + '/assets/themes/*/*.svg')):
    occ = f.split('/')[-2]; name = os.path.basename(f)[:-4]
    assets[f'{occ}/{name}'] = 'data:image/svg+xml;charset=utf-8,' + urllib.parse.quote(open(f).read(), safe='')
open(SRC + '/js/theme-assets.js', 'w').write('/* Generated by scripts/build-single-file.py: theme illustrations from assets/themes/ inlined so the prototype can be one file. */\nconst THEME_SVGS = ' + json.dumps(assets, indent=0) + ';\n')
html = open(SRC + '/index.html').read()
css = open(SRC + '/css/app.css').read()
out = html.replace('<link rel="stylesheet" href="css/app.css">', '<style>\n' + css + '\n</style>')
def inline(m):
    js = open(os.path.join(SRC, m.group(1))).read()
    assert '</script' not in js.lower(), m.group(1)
    note = ' — edit the two values below to enable live play (publishable key only!)' if m.group(1) == 'config.js' else ''
    return '<script>\n/* ---- ' + m.group(1) + note + ' ---- */\n' + js + '\n</script>'
out = re.sub(r'<script src="([^"]+)"></script>', inline, out)
assert 'src="js/' not in out and 'href="css/' not in out and 'src="config.js"' not in out
open(OUT, 'w').write(out)
for extra in sys.argv[1:]: open(extra, 'w').write(out)
print(OUT, round(len(out) / 1024), 'KB')
