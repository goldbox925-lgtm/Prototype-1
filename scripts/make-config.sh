#!/usr/bin/env sh
# Writes config.js from environment variables (e.g. in a GitHub Actions / Netlify / Vercel build step).
#   SUPABASE_URL=https://abcd1234.supabase.co SUPABASE_PUBLISHABLE_KEY=sb_publishable_xxx sh scripts/make-config.sh
# Refuses secret keys: only the publishable (anon) key may ever be shipped to browsers.
set -eu
: "${SUPABASE_URL:?set SUPABASE_URL}"; : "${SUPABASE_PUBLISHABLE_KEY:?set SUPABASE_PUBLISHABLE_KEY}"
case "$SUPABASE_PUBLISHABLE_KEY" in sb_secret_*) echo "Refusing: that is a SECRET key. Use the publishable key." >&2; exit 1;; esac
case "$SUPABASE_PUBLISHABLE_KEY" in eyJ*)
  ROLE=$(printf '%s' "$SUPABASE_PUBLISHABLE_KEY" | cut -d. -f2 | tr '_-' '/+' | base64 -d 2>/dev/null | grep -o '"role":"[a-z_]*"' || true)
  [ "$ROLE" = '"role":"anon"' ] || { echo "Refusing: this JWT is not the anon key ($ROLE)." >&2; exit 1; };;
esac
DIR=$(cd "$(dirname "$0")/.." && pwd)
cat > "$DIR/config.js" <<CFG
/* Generated by scripts/make-config.sh — public values only (publishable key). */
window.PLAYMODE_CONFIG = {
  supabaseUrl: '$SUPABASE_URL',
  supabasePublishableKey: '$SUPABASE_PUBLISHABLE_KEY'
};
CFG
echo "config.js written for $SUPABASE_URL"
